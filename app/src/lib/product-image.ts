import "server-only";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

// Product images on disk: UPLOADS_DIR/products/<uuid>.webp. In Docker,
// UPLOADS_DIR is a volume (see docker-compose): it is included in the backups together with the DB.

export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;
// Longer side: enough for the catalog detail, light for lists.
const MAX_SIDE = 1200;
const ACCEPTED_FORMATS = new Set(["jpeg", "png", "webp"]);
// Cuts off huge images (e.g. a "decompression bomb") before processing them.
const MAX_INPUT_PIXELS = 50_000_000;

const FILE_PATTERN = /^[0-9a-f-]{36}\.webp$/;

function productsDir(): string {
  return path.resolve(process.env.UPLOADS_DIR || "uploads", "products");
}

/** File path on disk, or null if the name is not one generated by us. */
function filePath(fileName: string): string | null {
  return FILE_PATTERN.test(fileName)
    ? path.join(productsDir(), fileName)
    : null;
}

/** An empty file input arrives as a 0-byte File. */
export function hasUpload(value: FormDataEntryValue | null): value is File {
  return value instanceof File && value.size > 0;
}

export type ImageResult =
  | { ok: true; data: Buffer }
  | { ok: false; error: "imageTooLarge" | "imageInvalid" };

/**
 * Validates and optimizes: the format is read from the content (not from the name nor the
 * type the browser sends), rotated according to EXIF, shrunk to 1200 px and
 * saved as WebP without metadata (no GPS from the phone photo).
 */
export async function processProductImage(file: File): Promise<ImageResult> {
  if (file.size > MAX_IMAGE_BYTES) return { ok: false, error: "imageTooLarge" };
  const input = Buffer.from(await file.arrayBuffer());
  try {
    const image = sharp(input, { limitInputPixels: MAX_INPUT_PIXELS });
    const { format } = await image.metadata();
    if (!format || !ACCEPTED_FORMATS.has(format)) {
      return { ok: false, error: "imageInvalid" };
    }
    const data = await image
      .rotate()
      .resize({
        width: MAX_SIDE,
        height: MAX_SIDE,
        fit: "inside",
        withoutEnlargement: true,
      })
      .webp({ quality: 80 })
      .toBuffer();
    return { ok: true, data };
  } catch {
    return { ok: false, error: "imageInvalid" };
  }
}

/** Saves under a new name: changing the image changes the URL (and the cache). */
export async function saveProductImage(data: Buffer): Promise<string> {
  const fileName = `${randomUUID()}.webp`;
  await mkdir(productsDir(), { recursive: true });
  await writeFile(path.join(productsDir(), fileName), data);
  return fileName;
}

/** Deletes without failing: if the file is already gone, there is nothing to do. */
export async function deleteProductImage(
  fileName: string | null | undefined,
): Promise<void> {
  const target = fileName ? filePath(fileName) : null;
  if (target) await rm(target, { force: true }).catch(() => {});
}

export async function readProductImage(
  fileName: string,
): Promise<Buffer | null> {
  const target = filePath(fileName);
  if (!target) return null;
  return readFile(target).catch(() => null);
}
